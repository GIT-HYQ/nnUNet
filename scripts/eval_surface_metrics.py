#!/usr/bin/env python3
"""E4 — HD95 / ASSD surface metrics on the hold-out predictions (paper §3.2).

Computes, per case and per GT-present class, the 95th-percentile Hausdorff
distance (HD95) and average symmetric surface distance (ASSD) between the
production ensemble prediction and the reference segmentation, then aggregates
over the paper's three reporting cohorts (72 / 69 / 66).

Pure scipy (scipy.ndimage.distance_transform_edt) -- no new dependencies on
the training server.  Expects:
  PRED_DIR/<case>.nii.gz   production predictions (id-assigner output)
  GT_DIR/<case>.nii.gz     reference labels, same space/shape (preprocessed GT)

Usage:
  python scripts/eval_surface_metrics.py                # full 72-case run
  python scripts/eval_surface_metrics.py --smoke        # 2 cases, 1 worker
  python scripts/eval_surface_metrics.py --jobs 8
  python scripts/eval_surface_metrics.py --pred-dir ... --gt-dir ...

Outputs (written next to the predictions):
  per_case_surface_metrics.jsonl   per-case, per-class HD95/ASSD
  surface_metrics.json             cohort aggregates (72/69/66)
"""
import argparse
import json
import os
import sys
import time
from multiprocessing import Pool

import numpy as np

BASE = "/home/share/clr/share/work/CBCT/nnUNet"
DEFAULT_PRED = f"{BASE}/tooth_3d_semantic/eval/holdout_ensemble_noxmirror_assigned/predictions"
DEFAULT_GT = f"{BASE}/tooth_3d_semantic/preprocessed/Dataset1000_ToothSemanticRAS/gt_segmentations"
DEFAULT_SPLIT = "/home/share/clr/share/data/CBCT/tooth_fairy2_m/list/tooth_split_k5_seed0.yaml"
# Local (repo) copy of the fixed 66-case census list, used for the 66-cohort
# aggregate.  Generated by scripts/lr_census_66.py.
CENSUS66_FALLBACK_GLOB = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                      "..", "tooth_3d_semantic", "logs", "lr_census_66.jsonl")
N_CLASSES = 32
SURFACE_PERCENTILE = 95.0


def _surface_distances(mask_a: np.ndarray, mask_b: np.ndarray, spacing) -> tuple[np.ndarray, np.ndarray]:
    """Distances from A's surface voxels to B, and B's to A (world mm).

    Uses the exact Euclidean distance transform of the complement; the
    "surface" of A is its boundary voxels (voxels of A with at least one
    6-neighbour outside A), sampled at their EDT-to-B distance.  Spacing
    makes the transform anisotropy-correct (mm, not voxels).
    """
    from scipy import ndimage

    edt_b = ndimage.distance_transform_edt(~mask_b, sampling=spacing)  # dist to B
    edt_a = ndimage.distance_transform_edt(~mask_a, sampling=spacing)  # dist to A

    def boundary(mask):
        er = ndimage.binary_erosion(mask, structure=ndimage.generate_binary_structure(3, 1),
                                    border_value=0)
        return mask & ~er

    surf_a, surf_b = boundary(mask_a), boundary(mask_b)
    return edt_b[surf_a], edt_a[surf_b]


def case_surface_metrics(pred: np.ndarray, gt: np.ndarray, spacing) -> dict:
    """Per-class HD95/ASSD for every GT-present class, plus foreground."""
    spacing = tuple(float(s) for s in spacing)
    out = {"per_class": {}, "foreground": {}}
    fg_a_d, fg_b_d = [], []
    for c in range(1, N_CLASSES + 1):
        g = gt == c
        if g.sum() == 0:
            continue
        p = pred == c
        da, db = _surface_distances(p, g, spacing)
        both = np.concatenate([da, db])
        out["per_class"][str(c)] = {
            "hd95_mm": float(np.percentile(both, SURFACE_PERCENTILE)),
            "assd_mm": float(both.mean()),
            "n_surf": int(both.size),
        }
        fg_a_d.append(da)
        fg_b_d.append(db)
    if fg_a_d:
        da = np.concatenate(fg_a_d)
        db = np.concatenate(fg_b_d)
        both = np.concatenate([da, db])
        out["foreground"] = {
            "hd95_mm": float(np.percentile(both, SURFACE_PERCENTILE)),
            "assd_mm": float(both.mean()),
        }
    return out


def _worker(job):
    case, pred_dir, gt_dir = job
    import SimpleITK as sitk

    pred_img = sitk.ReadImage(os.path.join(pred_dir, f"{case}.nii.gz"))
    gt_img = sitk.ReadImage(os.path.join(gt_dir, f"{case}.nii.gz"))
    pred = sitk.GetArrayFromImage(pred_img)
    gt = sitk.GetArrayFromImage(gt_img)
    if pred.shape != gt.shape:
        return {"case": case, "error": f"shape {pred.shape} != {gt.shape}"}
    res = case_surface_metrics(pred, gt, gt_img.GetSpacing())
    res["case"] = case
    print(f"  {case}: fg HD95 {res['foreground'].get('hd95_mm', float('nan')):.2f} mm "
          f"ASSD {res['foreground'].get('assd_mm', float('nan')):.2f} mm", flush=True)
    return res


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--pred-dir", default=DEFAULT_PRED)
    ap.add_argument("--gt-dir", default=DEFAULT_GT)
    ap.add_argument("--split-yaml", default=DEFAULT_SPLIT)
    ap.add_argument("--census66", default=CENSUS66_FALLBACK_GLOB,
                    help="jsonl with the fixed 66-case list (case field)")
    ap.add_argument("--jobs", type=int, default=1)
    ap.add_argument("--smoke", action="store_true", help="2 cases, 1 worker")
    args = ap.parse_args()

    import yaml
    with open(args.split_yaml) as fh:
        holdout = sorted(yaml.safe_load(fh)["holdout_test"])
    assert len(holdout) == 72, f"expected 72 holdout cases, got {len(holdout)}"

    census66 = None
    if os.path.exists(args.census66):
        with open(args.census66) as fh:
            census66 = {json.loads(l)["case"] for l in fh if l.strip()}
        print(f"66-cohort list: {len(census66)} cases from {args.census66}")
    else:
        print(f"WARNING: census66 list not found ({args.census66}); "
              "66-cohort aggregate will be skipped")

    cases = holdout[:2] if args.smoke else holdout
    out_dir = os.path.dirname(args.pred_dir.rstrip("/"))
    os.makedirs(out_dir, exist_ok=True)

    jobs = [(c, args.pred_dir, args.gt_dir) for c in cases]
    t0 = time.time()
    if args.jobs > 1 and not args.smoke:
        with Pool(args.jobs) as pool:
            rows = pool.map(_worker, jobs, chunksize=1)
    else:
        rows = [_worker(j) for j in jobs]
    ok = [r for r in rows if "error" not in r]
    err = [r for r in rows if "error" in r]
    print(f"\n{len(ok)} cases done, {len(err)} errors, {time.time() - t0:.0f}s")

    with open(os.path.join(out_dir, "per_case_surface_metrics.jsonl"), "w") as fh:
        for r in rows:
            fh.write(json.dumps(r) + "\n")

    def cohort(case_list):
        sel = [r for r in ok if r["case"] in set(case_list)]
        hd = [r["foreground"]["hd95_mm"] for r in sel if r["foreground"]]
        asd = [r["foreground"]["assd_mm"] for r in sel if r["foreground"]]
        return {
            "n": len(sel),
            "fg_hd95_mm_mean": round(float(np.mean(hd)), 3) if hd else None,
            "fg_hd95_mm_sd": round(float(np.std(hd, ddof=1)), 3) if len(hd) > 1 else None,
            "fg_assd_mm_mean": round(float(np.mean(asd)), 3) if asd else None,
            "fg_assd_mm_sd": round(float(np.std(asd, ddof=1)), 3) if len(asd) > 1 else None,
        }

    evaluable = [r["case"] for r in ok
                 if r["foreground"] and any(v.get("n_surf", 0) > 0 for v in r["per_class"].values())]
    agg = {
        "pred_dir": args.pred_dir,
        "gt_dir": args.gt_dir,
        "percentile": SURFACE_PERCENTILE,
        "cohorts": {
            "72": cohort(holdout),
            "69_evaluable": cohort(evaluable),
        },
        "per_class": {},
    }
    if census66:
        agg["cohorts"]["66_prespecified"] = cohort(census66)
    # Per-class mean HD95/ASSD over evaluable cases.
    for c in range(1, N_CLASSES + 1):
        vals_hd = [r["per_class"][str(c)]["hd95_mm"] for r in ok if str(c) in r["per_class"]]
        vals_as = [r["per_class"][str(c)]["assd_mm"] for r in ok if str(c) in r["per_class"]]
        if vals_hd:
            agg["per_class"][str(c)] = {
                "hd95_mm_mean": round(float(np.mean(vals_hd)), 3),
                "assd_mm_mean": round(float(np.mean(vals_as)), 3),
                "n": len(vals_hd),
            }
    with open(os.path.join(out_dir, "surface_metrics.json"), "w") as fh:
        json.dump(agg, fh, indent=2)
    print(f"Wrote {os.path.join(out_dir, 'surface_metrics.json')}")
    print(json.dumps(agg["cohorts"], indent=2))


if __name__ == "__main__":
    main()
